    # Create the final DataFrame
    df_table1 = pd.DataFrame(comparison_list, columns=['Network', 'Metric', 'Initial State (Dijkstra)', 'Final State (SRA)', 'Change (%)'])

    print("\n--- Generated Table 1 (with Gini Coefficient) ---")
