import pandas as pd
import numpy as np

def calculate_gini(x):
    """
    Calculates the Gini coefficient of a numpy array.
    Based on the formula: G = sum(|x_i - x_j|) / (2 * n * sum(x))
    A more efficient way is used here.
    """
    # Requires a 1D array, convert if it's a pandas Series
    x = np.asarray(x)
    # The array must not be empty
    if x.size == 0:
        return np.nan
    # All values must be non-negative
    if np.any(x < 0):
        return np.nan
    # Values cannot all be zero
    if np.sum(x) == 0:
        return 0.0 # Gini of all zeros is 0 (perfect equality)

    # Sort array and calculate Gini
    sorted_x = np.sort(x)
    n = len(x)
    cumx = np.cumsum(sorted_x, dtype=float)
    # The Gini coefficient is the area between the Lorenz curve and the line of equality
    return (n + 1 - 2 * np.sum(cumx) / cumx[-1]) / n

def generate_table_1_with_gini(runs_file, node_stats_file):
    """
    Generates the data for Table 1, including the Gini coefficient.
    """
    print("--- Starting: Generate Table 1 with Gini Coefficient ---")
    try:
        df_runs = pd.read_csv(runs_file)
        df_nodes = pd.read_csv(node_stats_file)
        print("Successfully loaded data files.")
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        print("Please ensure you have run 'run_final_simulation.py' first to generate the data.")
        return

    # Calculate aggregate stats from the node data
    # Group by run_id and calculate peak, std dev, and gini for centrality
    node_agg_stats = df_nodes.groupby('run_id')['final_betweenness_centrality'].agg(
        peak_centrality='max',
        std_centrality='std',
        gini_centrality=lambda x: calculate_gini(x)
    ).reset_index()

    # Merge these stats back into the main runs dataframe
    df_analysis = pd.merge(df_runs, node_agg_stats, on='run_id')

    # --- Now, build the final comparison table ---
    comparison_list = []
