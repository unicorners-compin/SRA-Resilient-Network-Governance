# (create_network 和 calculate_avg_hop_count 函数与之前相同，此处省略以保持简洁)
def create_network(network_type, n_nodes=100, seed=42):
    """Creates a network graph based on its type."""
    # ... (代码与上一版完全相同) ...
    if network_type == 'ER': return nx.erdos_renyi_graph(n_nodes, 0.1, seed=seed)
    elif network_type == 'BA': return nx.barabasi_albert_graph(n_nodes, 4, seed=seed)
    elif network_type == 'WS': return nx.watts_strogatz_graph(n_nodes, 8, 0.1, seed=seed)
    else: raise ValueError("Unknown network type specified.")

def calculate_avg_hop_count(graph, weight_key=None):
    """Calculates the average hop count (unweighted path length)."""
    # ... (代码与上一版完全相同) ...
    path_lengths = []
    path_iterator = nx.all_pairs_dijkstra_path(graph, weight=weight_key) if weight_key else nx.all_pairs_shortest_path(graph)
    for _, paths in path_iterator:
        for _, path in paths.items():
            path_lengths.append(len(path) - 1)
    return np.mean(path_lengths) if path_lengths else 0


def run_dijkstra_simulation(graph, network_type, run_id):
    """Gets all metrics for the baseline Dijkstra algorithm."""
    # ... (代码与上一版完全相同) ...
    centrality = nx.betweenness_centrality(graph, weight=None, normalized=False)
    avg_path_length = calculate_avg_hop_count(graph, weight_key=None)
    node_stats_records = []
    for node_id, cent_value in centrality.items():
        node_stats_records.append({
            'run_id': run_id, 'node_id': node_id,
            'final_betweenness_centrality': cent_value,
            'final_cost_C': 1.0  # 成本为1
        })
    return node_stats_records, avg_path_length


def run_sra_simulation(graph, network_type, run_id, alpha, beta_i, max_iter, tol):
    """Runs SRA and records both evolution and final state metrics."""
    # ... (代码与上一版大部分相同, 仅在最后增加返回最终成本C) ...
    n_nodes = graph.number_of_nodes()
    S = np.zeros(n_nodes)
    C = np.ones(n_nodes)
    evolution_records = []

    for k in tqdm(range(max_iter), desc=f"SRA on {network_type}"):
        for u, v in graph.edges(): graph.edges[u, v]['weight'] = (C[u] + C[v]) / 2.0
        centrality = nx.betweenness_centrality(graph, weight='weight', normalized=False)
        centrality_array = np.array([centrality.get(i, 0.0) for i in range(n_nodes)])
        peak_centrality = centrality_array.max()
        avg_path_length = calculate_avg_hop_count(graph, weight_key='weight')
        evolution_records.append({'run_id': run_id, 'iteration': k, 'peak_centrality': peak_centrality, 'avg_path_length': avg_path_length})
        norm_centrality = centrality_array / peak_centrality if peak_centrality > 0 else np.zeros(n_nodes)
        S_prev = S.copy()
        S = (1 - alpha) * S + alpha * norm_centrality
        C = 1 + beta_i * S
        if np.linalg.norm(S - S_prev, np.inf) < tol: break

    final_node_stats_records = []
    for node_id, cent_value in centrality.items():
        final_node_stats_records.append({
            'run_id': run_id, 'node_id': node_id,
            'final_betweenness_centrality': cent_value,
            'final_cost_C': C[node_id]  # !! 新增：记录最终成本C !!
        })

    return evolution_records, final_node_stats_records

