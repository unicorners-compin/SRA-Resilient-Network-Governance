        # Add the new Gini Coefficient row
        comparison_list.append([network_type, 'Gini of Centrality', initial_state['gini_centrality'], final_state['gini_centrality'], f"{get_change(final_state['gini_centrality'], initial_state['gini_centrality']):.2f}%"])
