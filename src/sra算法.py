def plot_path_change_figure(node_stats_file, agg_runs_file):
    """
    Generates Figure 4.3, visualizing the path change before and after SRA
    on a BA network.
    """
    print("--- Starting: Generate Figure 4.3 (Path Change Visualization) ---")
    try:
        df_nodes = pd.read_csv(node_stats_file)
        df_runs = pd.read_csv(agg_runs_file)
    except FileNotFoundError as e:
        print(f"ERROR: {e}\nPlease run the updated simulation script first.")
        return

    # --- 1. Setup and Find Initial Path ---
    NETWORK_TYPE = 'BA'
    G = nx.barabasi_albert_graph(100, 4, seed=42)

    dijkstra_run_id = df_runs.loc[(df_runs['network_type'] == NETWORK_TYPE) & (df_runs['algorithm'] == 'Dijkstra'), 'run_id'].iloc[0]
    dijkstra_nodes = df_nodes[df_nodes['run_id'] == dijkstra_run_id]

    hub_node = dijkstra_nodes.loc[dijkstra_nodes['final_betweenness_centrality'].idxmax()]['node_id']

    s, t, initial_path = None, None, None
    for source in range(100):
        for dest in range(source + 1, 100):
            path = nx.shortest_path(G, source=source, target=dest)
            if hub_node in path and source != hub_node and dest != hub_node:
                s, t, initial_path = source, dest, path
                break
        if initial_path:
            break

    if not initial_path:
        print("Could not find a suitable path through the hub. Exiting.")
        return

    print(f"Found initial path from {s} to {t} via hub {hub_node}: {initial_path}")

    # --- 2. Find SRA-Optimized Path ---
    sra_run_id = df_runs.loc[(df_runs['network_type'] == NETWORK_TYPE) & (df_runs['algorithm'] == 'SRA'), 'run_id'].iloc[0]
    sra_nodes = df_nodes[df_nodes['run_id'] == sra_run_id]

    # Create a dictionary of node costs from the data
    sra_costs = sra_nodes.set_index('node_id')['final_cost_C'].to_dict()

    # Set edge weights based on SRA costs
    for u, v in G.edges():
        G.edges[u, v]['weight'] = (sra_costs.get(u, 1.0) + sra_costs.get(v, 1.0)) / 2.0

    sra_path = nx.shortest_path(G, source=s, target=t, weight='weight')
    print(f"Found SRA-optimized path: {sra_path}")

    # --- 3. Visualization ---
    plt.figure(figsize=(12, 12))
    pos = nx.spring_layout(G, seed=42)

    # Node colors and sizes
    node_colors = ['#1f78b4'] * 100
    node_sizes = [100] * 100
    node_colors[s] = node_colors[t] = 'gold'
    node_sizes[s] = node_sizes[t] = 400
    node_colors[hub_node] = 'crimson'
    node_sizes[hub_node] = 600

    nx.draw_networkx_nodes(G, pos, node_color=node_colors, node_size=node_sizes)
    nx.draw_networkx_edges(G, pos, alpha=0.2)

    # Draw paths
    initial_path_edges = list(zip(initial_path, initial_path[1:]))
    sra_path_edges = list(zip(sra_path, sra_path[1:]))

    nx.draw_networkx_edges(G, pos, edgelist=initial_path_edges, edge_color='red', width=2.5, style='dashed', label='Initial Path (Dijkstra)')
    nx.draw_networkx_edges(G, pos, edgelist=sra_path_edges, edge_color='green', width=2.5, label='Final Path (SRA)')

    plt.title('Figure 4.3: Microscopic Path Change on BA Network', fontsize=16)
    plt.legend()

    output_filename = 'figure_4_3_path_change_EN.png'
    plt.savefig(output_filename)
